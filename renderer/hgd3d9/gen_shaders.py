#!/usr/bin/env python3
"""gen_shaders.py - assembles the two ps_2_0 pixel shaders of the light pass into shaders.h (token arrays), so the build needs no HLSL compiler.

  w_ps     writes the interpolated texcoord 0 (the eye depth w of the pixel: texcoords are perspective-correct with the vertices' rhw) to the R32F target
  light_ps reads that depth, rebuilds the pixel's camera-space position from its screen position, and outputs the light colour with
           alpha = amp * max(0, 1 - |P - light| / radius)

Constants of light_ps: c0 = (cx, cy, 1/f, 0) the projection; c1 = light position (camera space); c2 = (1/radius, amp, 1, 0);
c3 = light colour; c5 = (1 / ramp width, 0, 0, 0), c2.w = ramp start; c4 = (W/scale, -ox/scale, H/scale, -oy/scale) window uv to game pixels.
Usage: gen_shaders.py [shaders.h]"""
import struct, sys

TEMP, INPUT, CONST, TEXTURE, COLOROUT, SAMPLER = 0, 1, 2, 3, 8, 10
OPS = {'mov': 1, 'add': 2, 'sub': 3, 'mad': 4, 'mul': 5, 'rcp': 6, 'rsq': 7, 'dp3': 8, 'min': 10, 'max': 11, 'texld': 0x42}

def regtok(kind, num, extra):
    return 0x80000000 | ((kind & 7) << 28) | (((kind >> 3) & 3) << 11) | num | extra

def dest(s):
    name, _, mask = s.partition('.')
    kind = {'r': TEMP, 'o': COLOROUT}[name[0]]; num = int(name[2:] if name.startswith('oC') else name[1:])
    m = 0
    for ch in (mask or 'xyzw'): m |= 1 << 'xyzw'.index(ch)
    return regtok(kind, num, m << 16)

def src(s):
    neg = s.startswith('-'); s = s.lstrip('-')
    name, _, sw = s.partition('.')
    kind = {'r': TEMP, 'c': CONST, 't': TEXTURE, 's': SAMPLER}[name[0]]; num = int(name[1:])
    sw = sw or 'xyzw'
    if len(sw) == 1: sw *= 4
    sw = (sw + sw[-1] * 4)[:4]
    sel = 0
    for i, ch in enumerate(sw): sel |= 'xyzw'.index(ch) << (i * 2)
    return regtok(kind, num, (sel << 16) | ((1 if neg else 0) << 24))

def asm(lines):
    out = [0xFFFF0200]
    for ln in lines:
        ln = ln.strip()
        if not ln: continue
        op, _, rest = ln.partition(' ')
        args = [a.strip() for a in rest.split(',')] if rest else []
        if op == 'dcl':                       # dcl t0 | dcl_2d s0
            out += [0x0200001F, 0x80000000, regtok(TEXTURE, int(args[0][1:]), 0xF << 16)]
        elif op == 'dcl_2d':
            out += [0x0200001F, 0x90000000, regtok(SAMPLER, int(args[0][1:]), 0xF << 16)]
        else:
            n = len(args)
            out += [OPS[op] | (n << 24), dest(args[0])] + [src(a) for a in args[1:]]
    out.append(0x0000FFFF)
    return out

W_PS = ['dcl t0', 'mov oC0, t0']
LIGHT_PS = [
    'dcl t0', 'dcl_2d s0',
    'texld r0, t0, s0',                 # r0.x = w of the pixel
    'mul r1.xy, t0, c4.xzzz',           # window uv * (W/scale, H/scale)
    'add r1.xy, r1, c4.yw',             # game pixel (gx, gy)
    'sub r1.xy, r1, c0',                # minus (cx, cy)
    'mul r1.xy, r1, c0.zzzz',           # / f
    'mul r1.xy, r1, r0.xxxx',           # * w
    'mov r1.z, r0.x',
    'sub r1.xyz, r1, c1',               # P - light
    'dp3 r2.x, r1, r1',
    'rsq r2.y, r2.x',                   # 1/d
    'rcp r2.y, r2.y',                   # d
    'mul r2.y, r2.y, c2.x',             # d / radius
    'sub r2.y, c2.z, r2.y',             # 1 - d / radius
    'max r2.y, r2.y, c0.w',             # clamp at 0
    'sub r2.z, r0.x, c2.w',             # the player's own weapon and the ground at the camera's feet are left alone:
    'mul r2.z, r2.z, c5.x',             # a ramp from w = c2.w up over 1 / c5.x
    'max r2.z, r2.z, c0.w',
    'min r2.z, r2.z, c2.z',
    'mul r2.y, r2.y, r2.z',
    'mul r2.y, r2.y, c2.y',             # * amp
    'mov r3, c3',
    'mov r3.w, r2.y',
    'mov oC0, r3',
]

def carr(name, toks):
    return 'static const unsigned int %s[%d] = {\n    %s };\n' % (name, len(toks), ', '.join('0x%08X' % t for t in toks))

if __name__ == '__main__':
    path = sys.argv[1] if len(sys.argv) > 1 else 'shaders.h'
    with open(path, 'w') as f:
        f.write('/* shaders.h - GENERATED by gen_shaders.py (ps_2_0 token streams). */\n#ifndef HG_SHADERS_H\n#define HG_SHADERS_H\n')
        f.write(carr('g_w_ps', asm(W_PS))); f.write(carr('g_light_ps', asm(LIGHT_PS))); f.write('#endif\n')
    print('wrote', path)
