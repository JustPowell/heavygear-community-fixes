#!/usr/bin/env python3
"""gen_d3d9_min.py - generate d3d9_min.h, the few Direct3D 9 declarations the d3d9 backend needs.

The freestanding clang build cannot include the full platform d3d9.h, so this script reads Wine or Windows SDK headers
and writes a small header with only the interfaces, methods, types and constants listed below. Vtable slots we do not
call are `void *` placeholders, so the indices stay right. The vtable indices are then checked against the well-known
Direct3D 9 slot numbers; a mismatch stops the build.

The output is generated at build time and not committed.
Usage: gen_d3d9_min.py [--d3d9-include HEADER_DIRECTORY] [--out d3d9_min.h] [--check]"""
import argparse, re, sys, os

# interface -> methods we call (everything else becomes a placeholder)
WANT_METHODS = {
    'IDirect3D9': ['Release', 'GetAdapterDisplayMode', 'CheckDeviceMultiSampleType', 'CreateDevice'],
    'IDirect3DDevice9': ['Release', 'TestCooperativeLevel', 'Reset', 'Present', 'CreateTexture', 'BeginScene', 'EndScene',
                         'Clear', 'SetViewport', 'SetRenderState', 'SetTexture', 'SetTextureStageState', 'SetSamplerState',
                         'DrawPrimitiveUP', 'SetFVF', 'GetBackBuffer', 'CreateOffscreenPlainSurface', 'GetRenderTargetData', 'CreateQuery',
                         'CreateDepthStencilSurface', 'SetRenderTarget', 'GetRenderTarget', 'SetDepthStencilSurface', 'GetDepthStencilSurface',
                         'CreatePixelShader', 'SetPixelShader', 'SetPixelShaderConstantF'],
    'IDirect3DTexture9': ['Release', 'GenerateMipSubLevels', 'LockRect', 'UnlockRect', 'GetSurfaceLevel'],
    'IDirect3DPixelShader9': ['Release'],
    'IDirect3DSurface9': ['Release', 'LockRect', 'UnlockRect'],
    'IDirect3DQuery9': ['Release', 'Issue', 'GetData'],
}
# types we pass values of, beyond those the method signatures mention
EXTRA_TYPES = ['D3DBLEND', 'D3DTEXTUREOP', 'D3DTEXTUREFILTERTYPE', 'D3DCMPFUNC', 'D3DCULL', 'D3DZBUFFERTYPE',
               'D3DTEXTUREADDRESS', 'D3DFOGMODE', 'D3DBLENDOP', 'D3DSHADEMODE', 'D3DFILLMODE', 'D3DBACKBUFFER_TYPE', 'D3DQUERYTYPE']
WANT_DEFINES = ['D3D_SDK_VERSION', 'D3DADAPTER_DEFAULT', 'D3DCREATE_SOFTWARE_VERTEXPROCESSING', 'D3DCREATE_HARDWARE_VERTEXPROCESSING',
                'D3DCREATE_FPU_PRESERVE', 'D3DCLEAR_TARGET', 'D3DCLEAR_ZBUFFER', 'D3DFVF_XYZRHW', 'D3DFVF_DIFFUSE', 'D3DFVF_SPECULAR', 'D3DFVF_TEX1',
                'D3DUSAGE_DYNAMIC', 'D3DUSAGE_RENDERTARGET', 'D3DUSAGE_AUTOGENMIPMAP', 'D3DLOCK_DISCARD', 'D3DLOCK_READONLY', 'D3DISSUE_END', 'D3DGETDATA_FLUSH', 'D3DPRESENT_INTERVAL_ONE', 'D3DPRESENT_INTERVAL_IMMEDIATE',
                'D3DTA_DIFFUSE', 'D3DTA_TEXTURE', 'D3DTA_CURRENT']
# independent check: vtable slot numbers as documented for Direct3D 9
KNOWN_SLOTS = {
    'IDirect3D9': {'Release': 2, 'GetAdapterDisplayMode': 8, 'CheckDeviceMultiSampleType': 11, 'CreateDevice': 16},
    'IDirect3DDevice9': {'Release': 2, 'TestCooperativeLevel': 3, 'Reset': 16, 'Present': 17, 'CreateTexture': 23, 'BeginScene': 41,
                         'EndScene': 42, 'Clear': 43, 'SetViewport': 47, 'SetRenderState': 57, 'SetTexture': 65,
                         'SetTextureStageState': 67, 'SetSamplerState': 69, 'DrawPrimitiveUP': 83, 'SetFVF': 89,
                         'GetBackBuffer': 18, 'CreateOffscreenPlainSurface': 36, 'GetRenderTargetData': 32, 'CreateQuery': 118,
                         'CreateDepthStencilSurface': 29, 'SetRenderTarget': 37, 'GetRenderTarget': 38, 'SetDepthStencilSurface': 39,
                         'GetDepthStencilSurface': 40, 'CreatePixelShader': 106, 'SetPixelShader': 107, 'SetPixelShaderConstantF': 109},
    'IDirect3DTexture9': {'Release': 2, 'GenerateMipSubLevels': 16, 'LockRect': 19, 'UnlockRect': 20, 'GetSurfaceLevel': 18},
    'IDirect3DPixelShader9': {'Release': 2},
    'IDirect3DSurface9': {'Release': 2, 'LockRect': 13, 'UnlockRect': 14},
    'IDirect3DQuery9': {'Release': 2, 'Issue': 6, 'GetData': 7},
}

PREAMBLE = r'''/* d3d9_min.h - GENERATED by gen_d3d9_min.py from Direct3D 9 headers. Do not edit; do not commit. */
#ifndef HG_D3D9_MIN_H
#define HG_D3D9_MIN_H
#include <stddef.h>
#include <stdint.h>
#define __MSABI_LONG(x) x
#define CONST const
#define STDMETHODCALLTYPE __stdcall
typedef uint32_t UINT, DWORD, ULONG;
typedef int32_t  LONG, HRESULT, BOOL, INT;
typedef void *HWND, *HANDLE;
typedef float FLOAT;
typedef struct GUID { uint32_t a; uint16_t b, c; uint8_t d[8]; } GUID;
typedef const GUID *REFIID;
typedef struct RECT { LONG left, top, right, bottom; } RECT;
typedef struct RGNDATA RGNDATA;
#define MAKEFOURCC(a, b, c, d) ((DWORD)(uint8_t)(a) | ((DWORD)(uint8_t)(b) << 8) | ((DWORD)(uint8_t)(c) << 16) | ((DWORD)(uint8_t)(d) << 24))
#define D3D_OK 0
#define HG_D3D_FAILED(hr) ((hr) < 0)
'''

def read(p):
    with open(p, encoding='latin1') as f: return f.read()

def interface_methods(src, name):
    """Ordered [(name, ret, args)] of one interface, as listed in the platform header's vtable."""
    m = re.search(
        r'DECLARE_INTERFACE(?:_IID)?_\(\s*%s\s*,.*?\)\s*\{(.*?)\n\};' % re.escape(name),
        src, re.S)
    if not m: sys.exit('interface %s not found' % name)
    out = []
    pat = r'STDMETHOD(?:_\(\s*([^,]+?)\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\(\s*THIS(?:_\s*(.*?))?\)\s*PURE;'
    for mm in re.finditer(pat, m.group(1), re.S):   # statements, not lines: some declarations span several lines
        ret = mm.group(1) or 'HRESULT'; nm = mm.group(2) or mm.group(3)
        args = re.sub(r'\s+', ' ', (mm.group(4) or '').strip())
        out.append((nm, ret, args))
    return out

def balanced_block(src, start):
    """Text from the '{' after `start` to its matching '}' (inclusive)."""
    i = src.index('{', start); depth = 0
    for j in range(i, len(src)):
        if src[j] == '{': depth += 1
        elif src[j] == '}':
            depth -= 1
            if depth == 0: return i, j
    sys.exit('unbalanced block')

def find_type(types_src, name):
    """Return the typedef text for a D3D type: an enum/struct block, or a one-line alias."""
    m = re.search(r'typedef\s+(?:enum|struct)\s+_?\w*\s*\{', types_src)
    for m in re.finditer(r'typedef\s+(enum|struct)\s+\w*\s*\{', types_src):
        i, j = balanced_block(types_src, m.start())
        tail = re.match(r'\s*([^;]*);', types_src[j + 1:])
        names = [n.strip().lstrip('*') for n in tail.group(1).split(',')]
        if name in names:
            body = '\n'.join(l for l in types_src[i:j + 1].split('\n') if not l.strip().startswith('#'))
            return 'typedef %s %s %s %s;' % (m.group(1), '_' + name if m.group(1) else '', body, name) if False else \
                   'typedef %s _%s %s %s;' % (m.group(1), name, body, name)
    m = re.search(r'^typedef\s+[\w ]+?\s+%s\s*;' % re.escape(name), types_src, re.M)
    return m.group(0) if m else None

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--d3d9-include', '--wine-include', dest='d3d9_include', default='/usr/include/wine/windows')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'd3d9_min.h'))
    ap.add_argument('--check', action='store_true', help='only verify slot numbers, write nothing')
    a = ap.parse_args()
    d3d9 = read(os.path.join(a.d3d9_include, 'd3d9.h'))
    types = read(os.path.join(a.d3d9_include, 'd3d9types.h'))
    caps = read(os.path.join(a.d3d9_include, 'd3d9caps.h'))
    allsrc = d3d9 + '\n' + types + '\n' + caps

    ifaces = {}
    for name, wanted in WANT_METHODS.items():
        ms = interface_methods(d3d9, name)
        idx = {m[0]: i for i, m in enumerate(ms)}
        for w in wanted:
            if w not in idx: sys.exit('%s has no method %s' % (name, w))
        for w, slot in KNOWN_SLOTS[name].items():
            if idx[w] != slot: sys.exit('%s.%s: Wine header says slot %d, expected %d' % (name, w, idx[w], slot))
        ifaces[name] = ms
    if a.check:
        print('vtable slots ok'); return

    # types mentioned by the wanted signatures
    need, seen = [], set()
    def want(t):
        if t in seen: return
        seen.add(t); need.append(t)
    for name, wanted in WANT_METHODS.items():
        for nm, ret, args in ifaces[name]:
            if nm in wanted:
                for t in re.findall(r'\b(D3D\w+)\b', args + ' ' + ret): want(t)
    signature_types = set(need)
    for t in EXTRA_TYPES: want(t); signature_types.add(t)
    blocks = {}
    i = 0
    while i < len(need):
        t = need[i]; i += 1
        text = find_type(types, t) or find_type(caps, t)
        if text is None:
            if t in signature_types: sys.exit('type %s not found in Wine headers' % t)
            continue          # an enum member or macro that only looked like a type
        blocks[t] = text
        for dep in re.findall(r'\b(D3D\w+)\b', text):
            if dep != t: want(dep)
    # emit in dependency order (a type after the types it uses)
    order, done = [], set()
    def emit(t):
        if t in done: return
        done.add(t)
        for dep in re.findall(r'\b(D3D\w+)\b', blocks[t]):
            if dep != t and dep in blocks: emit(dep)
        order.append(t)
    for t in need:
        if t in blocks: emit(t)

    out = [PREAMBLE]
    for t in order: out.append(blocks[t] + '\n')
    for d in WANT_DEFINES:
        matches = list(re.finditer(r'^#define\s+%s\b[^\n]*' % re.escape(d), allsrc, re.M))
        if d == 'D3D_SDK_VERSION':
            # Windows SDK headers list a debug-only value first under D3D_DEBUG_INFO.
            matches = [m for m in matches if '0x80000000' not in m.group(0)]
        m = matches[0] if matches else None
        if not m: sys.exit('define %s not found' % d)
        out.append(m.group(0).replace('__MSABI_LONG(', '(') )
    out.extend([
        '#define D3DCOLOR_ARGB(a,r,g,b) ((uint32_t)((((uint32_t)(a) & 0xffu) << 24) | (((uint32_t)(r) & 0xffu) << 16) | (((uint32_t)(g) & 0xffu) << 8) | ((uint32_t)(b) & 0xffu)))',
        '#define D3DCOLOR_XRGB(r,g,b) D3DCOLOR_ARGB(0xffu,r,g,b)',
    ])
    out.append('')
    fwd = set(WANT_METHODS)
    for name, wanted in WANT_METHODS.items():       # interfaces only named as pointers in a signature
        for nm, ret, args in ifaces[name]:
            if nm in wanted: fwd.update(re.findall(r'\b(IDirect3D\w+)\b', args + ' ' + ret))
    for name in sorted(fwd): out.append('typedef struct %s %s;' % (name, name))
    out.append('')
    for name, wanted in WANT_METHODS.items():
        out.append('typedef struct %sVtbl {' % name)
        for k, (nm, ret, args) in enumerate(ifaces[name]):
            if nm in wanted:
                arglist = (', ' + args) if args else ''
                out.append('    %s (STDMETHODCALLTYPE *%s)(%s *This%s);   /* %d */' % (ret, nm, name, arglist, k))
            else:
                out.append('    void *%s;   /* %d, not used */' % (nm, k))
        out.append('} %sVtbl;' % name)
        out.append('struct %s { const %sVtbl *lpVtbl; };' % (name, name))
        for w, slot in KNOWN_SLOTS[name].items():
            out.append('_Static_assert(offsetof(%sVtbl, %s) == %d * sizeof(void *), "%s.%s slot");' % (name, w, slot, name, w))
        out.append('')
    out.append('IDirect3D9 *__stdcall Direct3DCreate9(UINT SDKVersion);')
    out.append('#endif')
    with open(a.out, 'w') as f: f.write('\n'.join(out) + '\n')
    print('wrote', a.out, '(%d types, %d interfaces)' % (len(order), len(ifaces)))

main()
